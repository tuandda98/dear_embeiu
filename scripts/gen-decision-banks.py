#!/usr/bin/env python3
"""Sinh lib/data/dish_bank.dart + lib/data/activity_bank.dart từ 2 bảng PO
(project/features/decision-wheel/dish-bank.md + activity-bank.md).

Sửa nội dung ngân hàng = sửa file .md rồi chạy lại:
    python3 scripts/gen-decision-banks.py
Không sửa tay 2 file .dart sinh ra.
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SPEC = os.path.join(ROOT, "project", "features", "decision-wheel")


def rows(md_name, ncols):
    out = []
    with open(os.path.join(SPEC, md_name), encoding="utf-8") as f:
        for line in f:
            if not line.startswith("| "):
                continue
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if len(cells) != ncols or cells[0] == "id" or set(cells[0]) <= {"-"}:
                continue
            out.append(cells)
    return out


def dart_str(s):
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'"


def write(path, var, doc, items):
    ids = [i[0] for i in items]
    assert len(ids) == len(set(ids)), "trùng id"
    for i in ids:
        assert re.fullmatch(r"[a-z0-9_]+", i), i
    lines = [
        "// GENERATED by scripts/gen-decision-banks.py — do not edit by hand.",
        f"// Source: project/features/decision-wheel/{doc}",
        "",
        "import '../models/decision.dart';",
        "",
        f"/// {len(items)} items. Ids are stable (stored as `resultId`).",
        f"const List<DecisionBankItem> {var} = <DecisionBankItem>[",
    ]
    for item_id, vi, en, emoji, tags in items:
        tag_lit = ", ".join(dart_str(t) for t in tags)
        lines.append(
            f"  DecisionBankItem({dart_str(item_id)}, {dart_str(vi)}, "
            f"{dart_str(en)}, {dart_str(emoji)}, {{{tag_lit}}}),"
        )
    lines.append("];")
    with open(os.path.join(ROOT, path), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{path}: {len(items)}")


def split(v):
    return [t.strip() for t in v.split(",") if t.strip()]


dishes = []
for item_id, vi, en, meals, places, effort, emoji in rows("dish-bank.md", 7):
    dishes.append((item_id, vi, en, emoji, split(meals) + split(places) + split(effort)))

acts = []
for item_id, vi, en, place, cost, when, emoji in rows("activity-bank.md", 7):
    acts.append((item_id, vi, en, emoji, split(place) + split(cost) + split(when)))

write("lib/data/dish_bank.dart", "kDishBank", "dish-bank.md", dishes)
write("lib/data/activity_bank.dart", "kActivityBank", "activity-bank.md", acts)
